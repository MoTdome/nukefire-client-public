function clientCommandHelp(topicValue, prefixValue = DEFAULT_CLIENT_COMMAND_PREFIX) {
  const normalized = normalizeHelpTopic(topicValue);
  if (!normalized) return listClientCommandHelp(prefixValue);
  const topic = CLIENT_COMMAND_HELP_LOOKUP.get(normalized);
  const prefix = normalizedPrefix(prefixValue);
  if (!topic) {
    return [
      `No client help topic for "${normalized}".`,
      `Use ${prefix}help to list available client commands.`
    ];
  }

  const output = [
    `${prefix}${topic.name} — ${topic.summary}`,
    '',
    'SUMMARY',
    `  ${topic.summary}`,
    '',
    'USAGE'
  ];
  for (const usage of topic.usages) output.push(`  ${withPrefix(usage, prefix)}`);
  output.push('', 'NOTES');
  for (const detail of topic.details) output.push(`  ${detail}`);
  const aliases = topic.aliases.filter((alias) => alias !== topic.name);
  if (aliases.length > 0) {
    output.push('', `Related names: ${aliases.map((alias) => `${prefix}${alias}`).join(', ')}`);
  }
  return output;
}

