function normalizedPrefix(value) {
  return normalizeClientCommandPrefix(value, DEFAULT_CLIENT_COMMAND_PREFIX);
}

function normalizeHelpTopic(value) {
  return String(value || '')
    .normalize('NFKC')
    .trim()
    .toLowerCase()
    .replace(/^[#~^/]+/u, '')
    .replace(/[{}<>]/gu, '')
    .replace(/[^a-z0-9_-]+/gu, '-')
    .replace(/^-+|-+$/gu, '')
    .slice(0, 48);
}

function topicLookup() {
  const lookup = new Map();
  for (const topic of CLIENT_COMMAND_HELP_TOPICS) {
    lookup.set(topic.name, topic);
    for (const alias of topic.aliases) lookup.set(alias, topic);
  }
  return lookup;
}

const CLIENT_COMMAND_HELP_LOOKUP = topicLookup();

function withPrefix(usageValue, prefixValue) {
  const prefix = normalizedPrefix(prefixValue);
  const usage = String(usageValue || '');
  if (usage === '{prefix}{prefix}{server command}') {
    return `${prefix}${prefix}{server command}`;
  }
  return `${prefix}${usage}`;
}

